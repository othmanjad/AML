    private readonly ITestOutputHelper _out;
    public RuleEngineTests(ITestOutputHelper o) => _out = o;
    private void Actual(string s) => _out.WriteLine("ACTUAL: " + s);

    private static readonly TimeZoneInfo Amman = TimeZoneInfo.FindSystemTimeZoneById("Asia/Amman");
    private static readonly DateTime T0 = new(2026, 3, 10, 7, 0, 0, DateTimeKind.Utc);
    private long _id;

    private RuleTxn Tx(DateTime at, decimal amount, string dir = "out", string status = "Completed", string type = "P2P", string? channel = null,
        long? sender = null, long? receiver = null, string currency = "JOD", decimal? baseAmount = null, string fx = "SameCurrency", decimal reversed = 0,
        string? dest = null, string? src = null) => new()
    {
        Id = ++_id, SourceTransactionId = "T" + _id, TimestampUtc = at, Amount = amount, Currency = currency,
        BaseAmount = fx == "Missing" ? null : baseAmount ?? amount, BaseCurrency = "JOD", FxStatus = fx, Type = type, Status = status, Channel = channel,
        SenderCustomerId = sender ?? (dir == "out" ? 1 : 100 + _id), ReceiverCustomerId = receiver ?? (dir == "in" ? 1 : 100 + _id), Direction = dir,
        ReversedAmount = reversed, DestinationCountry = dest, SourceCountry = src
    };

    private static RuleDefinition Def(string json)
    {
        var (d, errors) = RuleValidator.ValidateJson(json, new Dictionary<string, string> { ["EXP_MONTHLY_CASH"] = "Decimal" });
        errors.Should().BeEmpty(string.Join("; ", errors.Select(e => e.Path + ": " + e.Message)));
        return d!;
    }

    private RuleEvaluationResult Run(RuleDefinition d, List<RuleTxn> txns, StubData? data = null, string? device = null) =>
        new RuleEvaluator(Amman).Evaluate(d, new RuleSubjectData { SubjectKey = "C1", CustomerId = 1, CustomerType = "Individual", DeviceId = device, Transactions = txns },
            T0.AddDays(-400), T0.AddDays(400), data ?? new StubData());

