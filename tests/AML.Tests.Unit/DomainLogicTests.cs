        errors.Should().NotBeEmpty();
        Actual("Validation errors: " + string.Join("; ", errors.Select(e => e.Message)));
    }

    [Fact, Tc("TC-RUL-003", "AML-TC-0105")]
    public void Sql_text_in_value_is_literal()
    {
        var d = Def("""{"condition":{"field":"txn.remarks","operator":"eq","value":"1' OR 1=1 -- DROP TABLE"}}""");
        var t = Tx(T0, 10);
        var r = Run(d, new List<RuleTxn> { t });
        r.Matches.Should().BeEmpty("the SQL text is compared as a literal string");
        var lit = new RuleTxn { Id = 99, SourceTransactionId = "X", TimestampUtc = T0, Amount = 1, Status = "Completed", Remarks = "1' OR 1=1 -- DROP TABLE", BaseAmount = 1, Direction = "out" };
        Run(d, new List<RuleTxn> { lit }).Matches.Should().HaveCount(1);
        Actual("SQL-like value accepted only as a typed string literal; matched only the transaction whose remarks equal the literal; no SQL is generated by the engine (in-memory interpreter).");
    }

