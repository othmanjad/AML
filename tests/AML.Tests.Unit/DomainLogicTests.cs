    [Theory, Tc("AML-TC-0216")]
    [InlineData(0.85)]
    public void Threshold_boundaries(double threshold)
    {
        var t = (decimal)threshold;
        static bool Hit(decimal score, decimal th) => score >= th;
        Hit(t - 0.0001m, t).Should().BeFalse();
        Hit(t, t).Should().BeTrue();
        Hit(t + 0.0001m, t).Should().BeTrue();
        Actual($"Score below threshold {t} → no hit; equal → hit; above → hit (>= semantics used by screening).");
    }

    public static readonly (string A, string B, bool Same)[] Labelled =
    {
        ("Mohammed Ali", "Muhammad Ali", true), ("Mohamad Hassan", "Mohammed Hasan", true), ("أحمد علي", "احمد علي", true),
        ("فاطمة الزهراء", "فاطمه الزهراء", true), ("Abdullah bin Khalid", "Abd Allah Khaled", true), ("Yousef Saleh", "Yusuf Salih", true),
        ("مصطفى كمال", "مصطفي كمال", true), ("Omar Khaled", "Umar Khalid", true), ("محمد عبدالله", "Mohammed Abdullah", true),
        ("Hussein Ahmad", "Husain Ahmed", true), ("Ibrahim Nasser", "Ebrahim Naser", true), ("Zorvan Testlisted Qadir", "Zorvan Qadir", true),
        ("Mohammed Ali", "Khalid Saeed", false), ("Fatima Noor", "Layla Hassan", false), ("Omar Khaled", "Amer Khalaf", false),
        ("أحمد علي", "سامي يوسف", false), ("ACME Trading", "Zenith Foods", false), ("Yousef Saleh", "Yasmin Saad", false),
        ("Hussein Ahmad", "Hisham Adel", false), ("Kareem Fakename", "Karim Fadel", false),
    };

    [Fact, Tc("TC-L10N-009", "AML-TC-0217")]
    public void Labelled_regression_set()
    {
        const decimal threshold = 0.85m;
        int tp = 0, fp = 0, fn = 0, tn = 0;
        foreach (var (a, b, same) in Labelled)
        {
            var hit = Matcher.Match(a, b).Score >= threshold;
            if (hit && same) tp++; else if (hit) fp++; else if (same) fn++; else tn++;
        }
        var precision = tp + fp == 0 ? 1 : (double)tp / (tp + fp);
        var recall = (double)tp / (tp + fn);
        const double baselinePrecision = 0.9, baselineRecall = 0.8;
        Actual($"Labelled set n={Labelled.Length} threshold={threshold}: TP={tp} FP={fp} FN={fn} TN={tn}; precision={precision:0.00} recall={recall:0.00} (baseline P≥{baselinePrecision} R≥{baselineRecall}).");
        precision.Should().BeGreaterThanOrEqualTo(baselinePrecision);
        recall.Should().BeGreaterThanOrEqualTo(baselineRecall);
    }
